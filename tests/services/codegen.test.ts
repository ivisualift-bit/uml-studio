import { describe, expect, it } from 'vitest';
import { execFileSync } from 'node:child_process';
import ts from 'typescript';
import { parse as parseJava } from 'java-parser';
import { generateCode } from '@/services/codegen';
import { instantiateTemplate } from '@/services/templates/templates';
import { ProjectBuilder } from '@/services/templates/builder';
import { sequentialIds } from '@/domain/ids';

function tricky() {
  const b = new ProjectBuilder('Tricky', { idPrefix: 'tricky' });
  const d = b.diagram('class', 'D');
  const pkg = b.node(d, 'package', 'école', 0, 0, { width: 600, height: 400 });
  const shape = b.node(d, 'class', 'Shape', 20, 40, {
    patch: { isAbstract: true, documentation: 'A shape */ with "quotes"' },
  });
  b.attribute(shape.elementId, '- class: String = hello world');
  b.attribute(shape.elementId, '+ count: Integer = 0');
  b.attribute(shape.elementId, '# tags: String [0..*]');
  b.operation(shape.elementId, '+ area(): Real', { isAbstract: true });
  const circle = b.node(d, 'class', 'Circle', 300, 40);
  b.attribute(circle.elementId, '- radius: Real = 1.5');
  b.operation(circle.elementId, '+ area(): Real');
  b.operation(circle.elementId, '+ scale(factor: Real = 2, out result: Circle): Circle');
  const drawable = b.node(d, 'interface', 'Drawable', 20, 250);
  b.operation(drawable.elementId, '+ draw(canvas: Money): void');
  b.attribute(drawable.elementId, '+ visible: Boolean');
  const color = b.node(d, 'enumeration', 'Color', 300, 250);
  b.literal(color.elementId, 'RED').literal(color.elementId, 'class');
  b.connect(d, 'generalization', circle.viewId, shape.viewId);
  b.connect(d, 'realization', circle.viewId, drawable.viewId);
  b.connect(d, 'association', circle.viewId, color.viewId, {
    targetEnd: { name: 'color', multiplicity: '1', navigability: 'navigable' },
  });
  void pkg;
  return b.build();
}

const docs = () =>
  [
    ['library', instantiateTemplate('library', sequentialIds('cg-lib'), new Date())],
    ['ecommerce', instantiateTemplate('ecommerce', sequentialIds('cg-eco'), new Date())],
    ['tricky', tricky()],
  ] as const;

describe('TypeScript generator', () => {
  it.each(docs())('%s: emits syntactically valid, type-correct TypeScript', (_name, doc) => {
    const { files } = generateCode(doc, 'typescript');
    expect(files.length).toBeGreaterThan(0);
    const host = ts.createCompilerHost({});
    const sources = new Map(files.map((f) => [`/gen/${f.path}`, f.content]));
    const original = host.getSourceFile.bind(host);
    host.getSourceFile = (fileName, languageVersion) => {
      const text = sources.get(fileName);
      return text !== undefined
        ? ts.createSourceFile(fileName, text, languageVersion, true)
        : original(fileName, languageVersion);
    };
    host.fileExists = (fileName) => sources.has(fileName) || ts.sys.fileExists(fileName);
    host.readFile = (fileName) => sources.get(fileName) ?? ts.sys.readFile(fileName);
    host.writeFile = () => undefined;
    host.useCaseSensitiveFileNames = () => true;
    host.getCanonicalFileName = (fileName) => fileName;
    host.directoryExists = (dir) => dir === '/gen' || ts.sys.directoryExists(dir);
    host.realpath = (path) => path;
    const program = ts.createProgram(
      [...sources.keys()],
      {
        strict: true,
        noEmit: true,
        target: ts.ScriptTarget.ES2022,
        module: ts.ModuleKind.ESNext,
        moduleResolution: ts.ModuleResolutionKind.Bundler,
        skipLibCheck: true,
        lib: ['lib.es2022.d.ts'],
      },
      host,
    );
    const diagnostics = ts
      .getPreEmitDiagnostics(program)
      .map((d) => `${d.file?.fileName}: ${ts.flattenDiagnosticMessageText(d.messageText, '\n')}`);
    expect(diagnostics).toEqual([]);
  });

  it('is deterministic and labels output as skeletons', () => {
    const doc = tricky();
    const a = generateCode(doc, 'typescript');
    const b = generateCode(doc, 'typescript');
    expect(a).toEqual(b);
    expect(a.files.every((f) => f.content.startsWith('// Generated by UML Studio — class skeleton'))).toBe(
      true,
    );
    const circle = a.files.find((f) => f.path === 'Circle.ts')!.content;
    expect(circle).toContain("import { Shape } from './Shape';");
    expect(circle).toContain('export class Circle extends Shape implements Drawable');
    expect(circle).toContain('private color!: Color;'); // association ends become private fields
    expect(circle).toContain("throw new Error('Not implemented: Circle.area')");
    const shape = a.files.find((f) => f.path === 'Shape.ts')!.content;
    expect(shape).toContain('export abstract class Shape');
    expect(shape).toContain('class_');
    expect(shape).toContain('"hello world"');
    expect(a.warnings.some((w) => w.includes('reserved'))).toBe(true);
  });
});

describe('Java generator', () => {
  it.each(docs())('%s: emits parseable Java with packages and types', (_name, doc) => {
    const { files } = generateCode(doc, 'java');
    for (const file of files) {
      expect(() => parseJava(file.content), file.path).not.toThrow();
    }
  });

  it('maps packages, inheritance and collections', () => {
    const { files } = generateCode(tricky(), 'java');
    const circle = files.find((f) => f.path.endsWith('Circle.java'))!;
    expect(circle.path).toBe('_cole/Circle.java'.replace('_cole', circle.path.split('/')[0]!));
    expect(circle.content).toContain('public class Circle extends Shape implements Drawable');
    expect(circle.content).toContain('throw new UnsupportedOperationException');
    const shape = files.find((f) => f.path.endsWith('Shape.java'))!.content;
    expect(shape).toContain('import java.util.List;');
    expect(shape).toContain('public abstract double area();');
  });
});

function python(): string | null {
  for (const candidate of ['python3', 'python']) {
    try {
      execFileSync(candidate, ['--version'], { stdio: 'ignore' });
      return candidate;
    } catch {
      // try next
    }
  }
  return null;
}

describe('Python generator', () => {
  const interpreter = python();
  it.each(docs())('%s: emits Python that ast.parse accepts', (_name, doc) => {
    const { files } = generateCode(doc, 'python', { dataclasses: true });
    expect(
      files.some((f) => f.content.includes('raise NotImplementedError') || f.content.includes('Enum')),
    ).toBe(true);
    if (!interpreter)
      throw new Error('A Python 3 interpreter is required for this test (python3 not found on PATH)');
    for (const file of files) {
      const out = execFileSync(
        interpreter,
        ['-I', '-c', 'import ast,sys; ast.parse(sys.stdin.read()); print("ok")'],
        { input: file.content, encoding: 'utf8' },
      );
      expect(out.trim(), file.path).toBe('ok');
    }
  });
});
