import type { ProjectDocument } from '@/domain/schemas/project';
import { extractModel, safeLiteral, sanitizeIdentifier, uniqueIn, type CgClassifier, type CgModel, type CgParam, type CgType, type GenerationResult } from './model';

const RESERVED = new Set(
  'break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with implements interface let package private protected public static yield await any boolean constructor declare get module require number set string symbol type from of unknown never object'.split(
    ' ',
  ),
);

const PRIMITIVES: Record<string, string> = {
  string: 'string',
  str: 'string',
  char: 'string',
  integer: 'number',
  int: 'number',
  long: 'number',
  short: 'number',
  byte: 'number',
  real: 'number',
  float: 'number',
  double: 'number',
  decimal: 'number',
  number: 'number',
  unlimitednatural: 'number',
  boolean: 'boolean',
  bool: 'boolean',
  date: 'Date',
  datetime: 'Date',
  void: 'void',
  object: 'unknown',
  any: 'unknown',
};

function docComment(text: string, indent = ''): string[] {
  if (!text.trim()) return [];
  return [`${indent}/**`, ...text.trim().replace(/\*\//g, '* /').split('\n').map((l) => `${indent} * ${l}`), `${indent} */`];
}

const visibility = (v: string) => (v === 'private' ? 'private ' : v === 'protected' ? 'protected ' : 'public ');

/** TypeScript class/interface/enum skeletons, one file per classifier. Output is deterministic. */
export function generateTypeScript(source: ProjectDocument | CgModel): GenerationResult {
  const model = 'classifiers' in source ? source : extractModel(source);
  const warnings: string[] = [];
  const names = new Map<string, string>();
  const usedFiles = new Set<string>();
  for (const c of model.classifiers) names.set(c.id, uniqueIn(usedFiles, sanitizeIdentifier(c.name, RESERVED, warnings, `Classifier "${c.name}"`, 'Unnamed')));

  const files = model.classifiers.map((c) => {
    const self = names.get(c.id)!;
    const typeRefs = new Set<string>();
    const valueRefs = new Set<string>();
    const typeName = (type: CgType | null): string => {
      if (!type) return 'void';
      let base: string;
      if (type.classifierId && names.has(type.classifierId)) {
        base = names.get(type.classifierId)!;
        if (type.classifierId !== c.id) typeRefs.add(base);
      } else if (!type.name) {
        base = 'unknown';
      } else {
        const primitive = PRIMITIVES[type.name.toLowerCase()];
        if (primitive) base = primitive;
        else {
          warnings.push(`${c.name}: type "${type.name}" is not a classifier of the model; emitted as unknown`);
          base = `unknown /* ${type.name.replace(/\*\//g, '')} */`;
        }
      }
      return type.collection ? `Array<${base}>` : base;
    };
    const parents = c.extends.map((id) => names.get(id)).filter((n): n is string => !!n);
    const interfaces = c.implements.map((id) => names.get(id)).filter((n): n is string => !!n);
    if (c.kind === 'class' && parents[0]) valueRefs.add(parents[0]);
    for (const n of [...parents, ...interfaces]) typeRefs.add(n);
    const body = renderClassifier(c, self, parents, interfaces, typeName, warnings);
    const imports = [...new Set([...typeRefs, ...valueRefs])]
      .filter((n) => n !== self)
      .sort()
      .map((n) => (valueRefs.has(n) ? `import { ${n} } from './${n}';` : `import type { ${n} } from './${n}';`));
    const content = ['// Generated by UML Studio — class skeleton (stubs only, not business logic).', ...imports, '', ...body, ''].join('\n');
    return { path: `${self}.ts`, content };
  });
  return { files, warnings };
}

function renderParams(list: CgParam[], typeName: (t: CgType | null) => string, warnings: string[], context: string): string {
  const used = new Set<string>();
  return list
    .map((p, i) => {
      const name = uniqueIn(used, sanitizeIdentifier(p.name || `arg${i}`, RESERVED, warnings, `${context} parameter`, `arg${i}`));
      const value = p.defaultValue ? safeLiteral(p.defaultValue, 'ts', warnings, `${context}.${name}`) : '';
      return `${name}: ${typeName(p.type)}${value ? ` = ${value}` : ''}`;
    })
    .join(', ');
}

function renderClassifier(c: CgClassifier, self: string, parents: string[], interfaces: string[], typeName: (t: CgType | null) => string, warnings: string[]): string[] {
  const out: string[] = [...docComment(c.documentation)];
  const used = new Set<string>();
  if (c.kind === 'enum') {
    out.push(`export enum ${self} {`);
    for (const l of c.literals) {
      const name = uniqueIn(used, sanitizeIdentifier(l, RESERVED, warnings, `${c.name}.${l}`, 'VALUE'));
      out.push(`  ${name} = ${JSON.stringify(name)},`);
    }
    out.push('}');
    return out;
  }
  if (c.kind === 'interface') {
    out.push(`export interface ${self}${parents.length ? ` extends ${parents.join(', ')}` : ''} {`);
    for (const f of c.fields) {
      const name = uniqueIn(used, sanitizeIdentifier(f.name, RESERVED, warnings, `${c.name}.${f.name}`));
      out.push(`  ${f.isReadOnly ? 'readonly ' : ''}${name}: ${typeName(f.type)};`);
    }
    for (const m of c.methods) {
      const name = uniqueIn(used, sanitizeIdentifier(m.name, RESERVED, warnings, `${c.name}.${m.name}()`));
      out.push(`  ${name}(${renderParams(m.params, typeName, warnings, `${c.name}.${name}`)}): ${typeName(m.returnType)};`);
    }
    out.push('}');
    return out;
  }
  if (parents.length > 1) warnings.push(`${c.name}: TypeScript has single class inheritance; only "${parents[0]}" is extended`);
  const abstract = c.isAbstract || c.methods.some((m) => m.isAbstract && !m.isStatic);
  out.push(`export ${abstract ? 'abstract ' : ''}class ${self}${parents[0] ? ` extends ${parents[0]}` : ''}${interfaces.length ? ` implements ${interfaces.join(', ')}` : ''} {`);
  for (const f of c.fields) {
    const name = uniqueIn(used, sanitizeIdentifier(f.name, RESERVED, warnings, `${c.name}.${f.name}`));
    const value = f.defaultValue ? safeLiteral(f.defaultValue, 'ts', warnings, `${c.name}.${name}`) : f.type.collection ? '[]' : '';
    out.push(`  ${visibility(f.visibility)}${f.isStatic ? 'static ' : ''}${f.isReadOnly ? 'readonly ' : ''}${name}${value || f.isStatic ? '' : '!'}: ${typeName(f.type)}${value ? ` = ${value}` : ''};`);
    if (f.isStatic && !value) warnings.push(`${c.name}.${name}: static field without default value is left undefined`);
  }
  for (const m of c.methods) {
    const name = uniqueIn(used, sanitizeIdentifier(m.name, RESERVED, warnings, `${c.name}.${m.name}()`));
    const isAbstract = m.isAbstract && !m.isStatic;
    const signature = `${visibility(m.visibility)}${m.isStatic ? 'static ' : ''}${isAbstract ? 'abstract ' : ''}${name}(${renderParams(m.params, typeName, warnings, `${c.name}.${name}`)}): ${typeName(m.returnType)}`;
    if (isAbstract) out.push('', `  ${signature};`);
    else out.push('', `  ${signature} {`, `    throw new Error('Not implemented: ${self}.${name}');`, '  }');
  }
  out.push('}');
  return out;
}
