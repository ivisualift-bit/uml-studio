import type { ProjectDocument } from '@/domain/schemas/project';
import {
  extractModel,
  safeLiteral,
  sanitizeIdentifier,
  uniqueIn,
  type CgClassifier,
  type CgModel,
  type CgParam,
  type CgType,
  type GenerationResult,
} from './model';

const RESERVED = new Set(
  'False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield match case type self'.split(
    ' ',
  ),
);

const PRIMITIVES: Record<string, string> = {
  string: 'str',
  str: 'str',
  char: 'str',
  integer: 'int',
  int: 'int',
  long: 'int',
  short: 'int',
  byte: 'int',
  real: 'float',
  float: 'float',
  double: 'float',
  decimal: 'Decimal',
  number: 'float',
  boolean: 'bool',
  bool: 'bool',
  date: 'date',
  datetime: 'datetime',
  void: 'None',
  object: 'Any',
  any: 'Any',
};

function snake(name: string): string {
  return (
    name
      .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
      .replace(/[^\p{L}\p{N}_]+/gu, '_')
      .toLowerCase()
      .replace(/^_+|_+$/g, '') || 'module'
  );
}

function docstring(text: string, indent: string): string[] {
  if (!text.trim()) return [];
  // Escape backslashes and every quote so no user text can terminate the docstring early.
  const safe = text.trim().replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return [`${indent}"""${safe.split('\n').join(`\n${indent}`)}"""`];
}

/** Python 3 skeletons: one module per classifier, ABC/abstractmethod, Enum, type annotations. */
export function generatePython(
  source: ProjectDocument | CgModel,
  options: { dataclasses?: boolean } = {},
): GenerationResult {
  const model = 'classifiers' in source ? source : extractModel(source);
  const warnings: string[] = [];
  const names = new Map<string, string>();
  const modules = new Map<string, string>();
  const usedModules = new Set<string>();
  for (const c of model.classifiers) {
    const name = sanitizeIdentifier(c.name, RESERVED, warnings, `Classifier "${c.name}"`, 'Unnamed');
    names.set(c.id, name);
    const pkg = c.packagePath.map((p) => {
      const s = snake(p);
      return RESERVED.has(s) ? `${s}_` : s;
    });
    modules.set(c.id, uniqueIn(usedModules, [...pkg, snake(name)].join('.')));
  }
  const packageDirs = new Set<string>();
  for (const m of modules.values()) {
    const parts = m.split('.').slice(0, -1);
    for (let i = 1; i <= parts.length; i += 1) packageDirs.add(parts.slice(0, i).join('/'));
  }

  const files = model.classifiers.map((c) => {
    const self = names.get(c.id)!;
    const module = modules.get(c.id)!;
    const typing = new Set<string>();
    const stdlib = new Set<string>();
    const runtimeImports = new Set<string>();
    const typeImports = new Set<string>();
    // Absolute imports from the generated root (add it to sys.path / PYTHONPATH).
    const importOf = (id: string) => `from ${modules.get(id)!} import ${names.get(id)}`;
    const typeName = (type: CgType | null): string => {
      if (!type) return 'None';
      let base: string;
      if (type.classifierId && names.has(type.classifierId)) {
        base = names.get(type.classifierId)!;
        if (type.classifierId !== c.id) typeImports.add(importOf(type.classifierId));
      } else {
        const p = PRIMITIVES[type.name.toLowerCase()];
        if (p) {
          base = p;
          if (p === 'Any') typing.add('Any');
          if (p === 'date') stdlib.add('from datetime import date');
          if (p === 'datetime') stdlib.add('from datetime import datetime');
          if (p === 'Decimal') stdlib.add('from decimal import Decimal');
        } else {
          if (type.name)
            warnings.push(
              `${c.name}: type "${type.name}" is not a classifier of the model; annotated as Any`,
            );
          typing.add('Any');
          base = 'Any';
        }
      }
      return type.collection ? `list[${base}]` : base;
    };
    for (const id of [...c.extends, ...c.implements])
      if (names.has(id) && id !== c.id) runtimeImports.add(importOf(id));
    const body = renderPython(c, self, names, typeName, warnings, options, typing, stdlib);
    const header = [
      '# Generated by UML Studio — class skeleton (stubs only, not business logic).',
      'from __future__ import annotations',
      '',
    ];
    const importLines = [
      ...[...stdlib].sort(),
      ...(typing.size ? [`from typing import ${[...typing].sort().join(', ')}`] : []),
    ];
    const typeOnly = [...typeImports].filter((i) => !runtimeImports.has(i)).sort();
    const lines = [...header, ...importLines];
    if (runtimeImports.size) lines.push(...[...runtimeImports].sort());
    if (typeOnly.length) {
      if (!typing.has('TYPE_CHECKING')) lines.push('from typing import TYPE_CHECKING');
      lines.push('', 'if TYPE_CHECKING:', ...typeOnly.map((i) => `    ${i}`));
    }
    lines.push('', '', ...body, '');
    return {
      path: `${module.replace(/\./g, '/')}.py`,
      content: lines.join('\n').replace(/\n{4,}/g, '\n\n\n'),
    };
  });
  for (const dir of [...packageDirs].sort())
    files.push({ path: `${dir}/__init__.py`, content: '# Generated by UML Studio\n' });
  return { files, warnings };
}

function renderParams(
  list: CgParam[],
  typeName: (t: CgType | null) => string,
  warnings: string[],
  context: string,
): string {
  const used = new Set<string>(['self', 'cls']);
  // Python forbids a required parameter after a defaulted one: such earlier defaults are dropped.
  let lastRequired = -1;
  list.forEach((p, i) => {
    if (!p.defaultValue) lastRequired = i;
  });
  return list
    .map((p, i) => {
      const name = uniqueIn(
        used,
        sanitizeIdentifier(snake(p.name || `arg${i}`), RESERVED, warnings, `${context} parameter`, `arg${i}`),
      );
      let value = '';
      if (p.defaultValue && i < lastRequired)
        warnings.push(
          `${context}.${name}: default "${p.defaultValue}" dropped (a required parameter follows it)`,
        );
      else if (p.defaultValue)
        value = ` = ${safeLiteral(p.defaultValue, 'python', warnings, `${context}.${name}`)}`;
      return `${name}: ${typeName(p.type)}${value}`;
    })
    .join(', ');
}

function renderPython(
  c: CgClassifier,
  self: string,
  names: Map<string, string>,
  typeName: (t: CgType | null) => string,
  warnings: string[],
  options: { dataclasses?: boolean },
  typing: Set<string>,
  stdlib: Set<string>,
): string[] {
  const out: string[] = [];
  const used = new Set<string>();
  if (c.kind === 'enum') {
    stdlib.add('from enum import Enum');
    out.push(`class ${self}(Enum):`, ...docstring(c.documentation, '    '));
    if (!c.literals.length) out.push('    pass');
    for (const l of c.literals) {
      const name = uniqueIn(used, sanitizeIdentifier(l, RESERVED, warnings, `${c.name}.${l}`, 'VALUE'));
      out.push(`    ${name} = ${JSON.stringify(name)}`);
    }
    return out;
  }
  const parents = [...c.extends, ...c.implements].map((id) => names.get(id)).filter((n): n is string => !!n);
  const isAbstract = c.kind === 'interface' || c.isAbstract || c.methods.some((m) => m.isAbstract);
  if (isAbstract) stdlib.add('from abc import ABC, abstractmethod');
  const bases = [...parents, ...(isAbstract && !parents.length ? ['ABC'] : [])];
  const useDataclass = !!options.dataclasses && c.kind === 'class' && c.methods.length === 0 && !isAbstract;
  if (useDataclass) {
    stdlib.add('from dataclasses import dataclass, field');
    out.push('@dataclass');
  }
  out.push(
    `class ${self}${bases.length ? `(${bases.join(', ')})` : ''}:`,
    ...docstring(c.documentation, '    '),
  );
  const attrName = (raw: string, visibility: string) => {
    const base = snake(raw);
    const prefixed = visibility === 'private' || visibility === 'protected' ? `_${base}` : base;
    return uniqueIn(used, sanitizeIdentifier(prefixed, RESERVED, warnings, `${c.name}.${raw}`));
  };
  const statics = c.fields.filter((f) => f.isStatic);
  const instance = c.fields.filter((f) => !f.isStatic);
  for (const f of statics) {
    const value = f.defaultValue
      ? safeLiteral(f.defaultValue, 'python', warnings, `${c.name}.${f.name}`)
      : 'None';
    typing.add('ClassVar');
    out.push(`    ${attrName(f.name, f.visibility)}: ClassVar[${typeName(f.type)}] = ${value}`);
  }
  if (useDataclass) {
    for (const f of instance) {
      const value = f.defaultValue
        ? safeLiteral(f.defaultValue, 'python', warnings, `${c.name}.${f.name}`)
        : f.type.collection
          ? 'field(default_factory=list)'
          : 'None';
      out.push(`    ${attrName(f.name, f.visibility)}: ${typeName(f.type)} | None = ${value}`);
    }
  } else if (instance.length) {
    out.push('', '    def __init__(self) -> None:');
    if (parents.length) out.push('        super().__init__()');
    for (const f of instance) {
      const value = f.defaultValue
        ? safeLiteral(f.defaultValue, 'python', warnings, `${c.name}.${f.name}`)
        : f.type.collection
          ? '[]'
          : 'None';
      const annotation =
        f.type.collection || f.defaultValue ? typeName(f.type) : `${typeName(f.type)} | None`;
      out.push(`        self.${attrName(f.name, f.visibility)}: ${annotation} = ${value}`);
    }
  }
  for (const m of c.methods) {
    const name = uniqueIn(
      used,
      sanitizeIdentifier(snake(m.name), RESERVED, warnings, `${c.name}.${m.name}()`),
    );
    const params = renderParams(m.params, typeName, warnings, `${c.name}.${name}`);
    const ret = typeName(m.returnType);
    out.push('');
    if (m.isStatic) out.push('    @staticmethod', `    def ${name}(${params}) -> ${ret}:`);
    else {
      if (m.isAbstract) out.push('    @abstractmethod');
      out.push(`    def ${name}(self${params ? `, ${params}` : ''}) -> ${ret}:`);
    }
    out.push(`        raise NotImplementedError(${JSON.stringify(`${self}.${name}`)})`);
  }
  if (!c.fields.length && !c.methods.length && !c.documentation.trim()) out.push('    pass');
  return out;
}
