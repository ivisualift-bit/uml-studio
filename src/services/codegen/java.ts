import type { ProjectDocument } from '@/domain/schemas/project';
import {
  extractModel,
  safeLiteral,
  sanitizeIdentifier,
  uniqueIn,
  type CgClassifier,
  type CgModel,
  type CgParam,
  type CgType,
  type GenerationResult,
} from './model';

const RESERVED = new Set(
  'abstract assert boolean break byte case catch char class const continue default do double else enum extends final finally float for goto if implements import instanceof int interface long native new package private protected public return short static strictfp super switch synchronized this throw throws transient try void volatile while true false null var record yield sealed permits'.split(
    ' ',
  ),
);

const PRIMITIVES: Record<string, { type: string; boxed: string; import?: string }> = {
  string: { type: 'String', boxed: 'String' },
  str: { type: 'String', boxed: 'String' },
  char: { type: 'char', boxed: 'Character' },
  integer: { type: 'int', boxed: 'Integer' },
  int: { type: 'int', boxed: 'Integer' },
  long: { type: 'long', boxed: 'Long' },
  short: { type: 'short', boxed: 'Short' },
  byte: { type: 'byte', boxed: 'Byte' },
  real: { type: 'double', boxed: 'Double' },
  double: { type: 'double', boxed: 'Double' },
  float: { type: 'float', boxed: 'Float' },
  decimal: { type: 'BigDecimal', boxed: 'BigDecimal', import: 'java.math.BigDecimal' },
  number: { type: 'double', boxed: 'Double' },
  boolean: { type: 'boolean', boxed: 'Boolean' },
  bool: { type: 'boolean', boxed: 'Boolean' },
  date: { type: 'LocalDate', boxed: 'LocalDate', import: 'java.time.LocalDate' },
  datetime: { type: 'LocalDateTime', boxed: 'LocalDateTime', import: 'java.time.LocalDateTime' },
  void: { type: 'void', boxed: 'Void' },
  object: { type: 'Object', boxed: 'Object' },
  any: { type: 'Object', boxed: 'Object' },
};

const packageSegment = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^\p{L}\p{N}_]/gu, '_')
    .replace(/^(\p{N})/u, '_$1');
const visibility = (v: string) => (v === 'package' ? '' : `${v} `);

/** Java skeletons: one public top-level type per file, packages from the UML package tree. */
export function generateJava(source: ProjectDocument | CgModel): GenerationResult {
  const model = 'classifiers' in source ? source : extractModel(source);
  const warnings: string[] = [];
  const names = new Map<string, string>();
  const packages = new Map<string, string>();
  const usedQualified = new Set<string>();
  for (const c of model.classifiers) {
    const pkg = c.packagePath.map((p) => {
      const seg = packageSegment(p);
      return RESERVED.has(seg) ? `${seg}_` : seg;
    });
    packages.set(c.id, pkg.join('.'));
    const simple = sanitizeIdentifier(c.name, RESERVED, warnings, `Classifier "${c.name}"`, 'Unnamed');
    const unique = uniqueIn(usedQualified, `${pkg.join('.')}:${simple}`).split(':')[1]!;
    names.set(c.id, unique);
  }

  const files = model.classifiers.map((c) => {
    const self = names.get(c.id)!;
    const pkg = packages.get(c.id)!;
    const imports = new Set<string>();
    const typeName = (type: CgType | null, boxed = false): string => {
      if (!type) return 'void';
      let base: string;
      if (type.classifierId && names.has(type.classifierId)) {
        base = names.get(type.classifierId)!;
        const otherPkg = packages.get(type.classifierId)!;
        if (otherPkg !== pkg && otherPkg) imports.add(`${otherPkg}.${base}`);
      } else {
        const p = PRIMITIVES[type.name.toLowerCase()];
        if (p) {
          base = boxed || type.collection ? p.boxed : p.type;
          if (p.import) imports.add(p.import);
        } else {
          if (type.name)
            warnings.push(
              `${c.name}: type "${type.name}" is not a classifier of the model; emitted as Object`,
            );
          base = 'Object';
        }
      }
      if (type.collection) {
        imports.add('java.util.List');
        return `List<${base === 'void' ? 'Object' : base}>`;
      }
      return base;
    };
    const body = renderJava(c, self, model, names, typeName, warnings);
    const lines = ['// Generated by UML Studio — class skeleton (stubs only, not business logic).'];
    if (pkg) lines.push(`package ${pkg};`, '');
    const sortedImports = [...imports].sort();
    if (sortedImports.length) lines.push(...sortedImports.map((i) => `import ${i};`), '');
    lines.push(...body, '');
    const dir = pkg ? `${pkg.replace(/\./g, '/')}/` : '';
    return { path: `${dir}${self}.java`, content: lines.join('\n') };
  });
  return { files, warnings };
}

function javadoc(text: string, indent = ''): string[] {
  if (!text.trim()) return [];
  return [
    `${indent}/**`,
    ...text
      .trim()
      .replace(/\*\//g, '* /')
      .split('\n')
      .map((l) => `${indent} * ${l}`),
    `${indent} */`,
  ];
}

function renderParams(
  list: CgParam[],
  typeName: (t: CgType | null) => string,
  warnings: string[],
  context: string,
): string {
  const used = new Set<string>();
  return list
    .map((p, i) => {
      const name = uniqueIn(
        used,
        sanitizeIdentifier(p.name || `arg${i}`, RESERVED, warnings, `${context} parameter`, `arg${i}`),
      );
      if (p.defaultValue)
        warnings.push(
          `${context}.${name}: Java has no default parameter values; "${p.defaultValue}" omitted`,
        );
      return `${typeName(p.type)} ${name}`;
    })
    .join(', ');
}

function renderJava(
  c: CgClassifier,
  self: string,
  model: CgModel,
  names: Map<string, string>,
  typeName: (t: CgType | null, boxed?: boolean) => string,
  warnings: string[],
): string[] {
  const out: string[] = [...javadoc(c.documentation)];
  const used = new Set<string>();
  const ref = (id: string) => {
    const n = names.get(id);
    const target = model.byId.get(id);
    if (n && target && target.packagePath.join('.') !== c.packagePath.join('.'))
      typeName({ name: target.name, collection: false, classifierId: id });
    return n;
  };
  if (c.kind === 'enum') {
    out.push(`public enum ${self} {`);
    const literals = c.literals.map((l) =>
      uniqueIn(used, sanitizeIdentifier(l, RESERVED, warnings, `${c.name}.${l}`, 'VALUE')),
    );
    if (literals.length) out.push(`    ${literals.join(',\n    ')}`);
    out.push('}');
    return out;
  }
  const parents = c.extends.map(ref).filter((n): n is string => !!n);
  const interfaces = c.implements.map(ref).filter((n): n is string => !!n);
  if (c.kind === 'interface') {
    out.push(`public interface ${self}${parents.length ? ` extends ${parents.join(', ')}` : ''} {`);
    for (const f of c.fields) {
      const name = uniqueIn(used, sanitizeIdentifier(f.name, RESERVED, warnings, `${c.name}.${f.name}`));
      // Interfaces cannot hold instance state: expose the attribute as an abstract accessor.
      const getter = `get${name[0]!.toUpperCase()}${name.slice(1)}`;
      warnings.push(`${c.name}.${f.name}: interface attribute generated as accessor ${getter}()`);
      out.push(`    ${typeName(f.type)} ${uniqueIn(used, getter)}();`);
    }
    for (const m of c.methods) {
      const name = uniqueIn(used, sanitizeIdentifier(m.name, RESERVED, warnings, `${c.name}.${m.name}()`));
      if (m.isStatic) {
        const ret = typeName(m.returnType);
        out.push(
          `    static ${ret} ${name}(${renderParams(m.params, typeName, warnings, `${c.name}.${name}`)}) {`,
          `        throw new UnsupportedOperationException("Not implemented: ${self}.${name}");`,
          '    }',
        );
      } else
        out.push(
          `    ${typeName(m.returnType)} ${name}(${renderParams(m.params, typeName, warnings, `${c.name}.${name}`)});`,
        );
    }
    out.push('}');
    return out;
  }
  if (parents.length > 1)
    warnings.push(`${c.name}: Java has single class inheritance; only "${parents[0]}" is extended`);
  const abstract = c.isAbstract || c.methods.some((m) => m.isAbstract && !m.isStatic);
  out.push(
    `public ${abstract ? 'abstract ' : c.isFinal ? 'final ' : ''}class ${self}${parents[0] ? ` extends ${parents[0]}` : ''}${interfaces.length ? ` implements ${interfaces.join(', ')}` : ''} {`,
  );
  for (const f of c.fields) {
    const name = uniqueIn(used, sanitizeIdentifier(f.name, RESERVED, warnings, `${c.name}.${f.name}`));
    const type = typeName(f.type);
    let init = '';
    if (f.defaultValue) init = ` = ${safeLiteral(f.defaultValue, 'java', warnings, `${c.name}.${name}`)}`;
    else if (f.type.collection) init = ' = new java.util.ArrayList<>()';
    else if (f.isReadOnly && f.isStatic) {
      warnings.push(`${c.name}.${name}: static final field without default; not marked final`);
    }
    const isFinal = f.isReadOnly && !!init;
    out.push(
      `    ${visibility(f.visibility)}${f.isStatic ? 'static ' : ''}${isFinal ? 'final ' : ''}${type} ${name}${init};`,
    );
  }
  for (const m of c.methods) {
    const name = uniqueIn(used, sanitizeIdentifier(m.name, RESERVED, warnings, `${c.name}.${m.name}()`));
    const ret = typeName(m.returnType);
    const isAbstract = m.isAbstract && !m.isStatic;
    const signature = `${visibility(m.visibility)}${m.isStatic ? 'static ' : ''}${isAbstract ? 'abstract ' : ''}${ret} ${name}(${renderParams(m.params, typeName, warnings, `${c.name}.${name}`)})`;
    out.push('');
    if (isAbstract) out.push(`    ${signature};`);
    else
      out.push(
        `    ${signature} {`,
        `        throw new UnsupportedOperationException("Not implemented: ${self}.${name}");`,
        '    }',
      );
  }
  out.push('}');
  return out;
}
